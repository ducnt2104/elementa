// High-performance O(1) card lookup cache
let cardLookupMap: Map<string, PlayableCardDef> | null = null;
function getLookupMap(): Map<string, PlayableCardDef> {
  if (!cardLookupMap) {
    cardLookupMap = new Map();
    for (const card of PLAYABLE_CARDS) {
      cardLookupMap.set(card.id, card);
    }
  }
  return cardLookupMap;
}

// Dynamic registry for user-crafted custom cards evaluated and approved by AI Guardrails
let customCardsRegistry: PlayableCardDef[] = [];

export const registerCustomCard = (card: PlayableCardDef) => {
  const existingIdx = customCardsRegistry.findIndex(c => c.id === card.id);
  if (existingIdx !== -1) {
    customCardsRegistry[existingIdx] = card;
  } else {
    customCardsRegistry.push(card);
  }
};

export const registerCustomCards = (cards: PlayableCardDef[]) => {
  cards.forEach(card => registerCustomCard(card));
};

export const clearCustomCards = () => {
  customCardsRegistry = [];
};

// Helper to look up card definitions across both canonical and custom crafted cards
export const getPlayableCardById = (id: string): PlayableCardDef | undefined => {
  return getLookupMap().get(id) || customCardsRegistry.find(c => c.id === id);
};

// Helper to return all available playable cards (canonical + approved custom creations)
export const getAllPlayableCards = (): PlayableCardDef[] => {
  return [...PLAYABLE_CARDS, ...customCardsRegistry];
};

